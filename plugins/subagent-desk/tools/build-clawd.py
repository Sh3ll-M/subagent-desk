"""Builds hooks/clawd.ts from the Clawd SVGs in assets/clawd (from clawd-tank, MIT).

Run after changing an SVG:  python -I tools/build-clawd.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'assets', 'clawd')
OUT = os.path.join(HERE, '..', 'hooks', 'clawd.ts')

FILES = {
    'debugger': 'clawd-working-debugger.svg',
    'typing': 'clawd-working-typing.svg',
    'building': 'clawd-working-building.svg',
    'wizard': 'clawd-working-wizard.svg',
    'conducting': 'clawd-working-conducting.svg',
    'beacon': 'clawd-working-beacon.svg',
    'thinking': 'clawd-working-thinking.svg',
    'happy': 'clawd-happy.svg',
    'idle': 'clawd-idle-living.svg',
    'dizzy': 'clawd-dizzy.svg',
    'confused': 'clawd-working-confused.svg',
}

table = {}
for anim, name in FILES.items():
    with open(os.path.join(SRC, name), encoding='utf-8') as f:
        svg = f.read()
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
    svg = re.sub(r'/\*.*?\*/', '', svg, flags=re.S)
    svg = re.sub(r'>\s+<', '><', svg).strip()
    svg = re.sub(r'\s{2,}', ' ', svg)
    assert '<script' not in svg and '<animate' not in svg, name
    assert len(svg) < 120_000, name
    table[anim] = svg

ts = f'''// Generated by tools/build-clawd.py from assets/clawd (clawd-tank, MIT). Do not edit by hand.
export type Anim = {' | '.join(json.dumps(k) for k in FILES)}

/** The body colour every Clawd SVG is drawn in. */
export const BODY_HEX = '#DE886D'

export const CLAWD: Record<Anim, string> = {json.dumps(table, indent=1)}

/** A Clawd animation in `color`, drawn `px` square. */
export function clawdSvg(anim: Anim, color: string, px: number): string {{
  return CLAWD[anim]
    .replace(/#de886d/gi, color)
    .replace(/^<svg([^>]*?)\\swidth="[^"]*"/, `<svg$1 width="${{px}}"`)
    .replace(/^(<svg[^>]*?)\\sheight="[^"]*"/, `$1 height="${{px}}"`)
}}
'''
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(ts)
print(f'{len(table)} animations, {sum(len(v) for v in table.values())} chars')
